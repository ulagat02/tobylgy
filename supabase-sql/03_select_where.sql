--  Не үйренесіз:
--    • select: қай бағандарды аламыз
--    • where: қай жолдарды аламыз (сүзгі)
--    • and / or / not, in, between, like / ilike, is null
--    • order by: сұрыптау, limit / offset: беттерге бөлу
--    • distinct, есептелген бағандар, as (бүркеншік ат)
--
--  Қалай орындау: сұрауларды БІР-БІРДЕН орындаңыз. Керек сұрауды
--  тышқанмен белгілеңіз (highlight) де, Run басыңыз: тек белгіленген
--  бөлік орындалады. Бүкіл файлды бірден орындасаңыз, SQL Editor тек
--  соңғы сұраудың нәтижесін көрсетеді.
--
--  Бұл сабақ деректі өзгертпейді, қалағаныңызша қайталай беріңіз.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 3.1. Барлық бағандар: *
-- ---------------------------------------------------------------------
select * from products;

-- order by жазылмаса, Postgres жолдарды кез келген ретпен қайтара алады.
-- Мысалы, 2-сабақта өзгерткен ақ Tamir диваны тізімнің соңына түсуі
-- мүмкін. Реті маңызды болса, әрдайым order by жазыңыз (3.8).


-- ---------------------------------------------------------------------
-- 3.2. Тек керек бағандар
-- ---------------------------------------------------------------------
-- Supabase-та да * орнына керек бағандарды атап алған дұрыс: жауап
-- жылдамырақ келеді әрі артық дерек жіберілмейді.
select name, color, price from products;


-- ---------------------------------------------------------------------
-- 3.3. where: сүзгі
-- ---------------------------------------------------------------------
-- Салыстыру операторлары:  =   <>   <   >   <=   >=
select name, color, price
from products
where price < 500000;                 -- 500 000 теңгеден арзан

select name, color, price
from products
where color = 'Графит';               -- мәтін бір тырнақшада: 'Графит'

select name, color, price
from products
where color <> 'Графит';              -- <> "тең емес" дегенді білдіреді


-- ---------------------------------------------------------------------
-- 3.4. and, or, not
-- ---------------------------------------------------------------------
select name, color, price
from products
where in_stock and price < 500000;    -- қоймада бар ЖӘНЕ 500 000-нан арзан

select name, color, badge
from products
where badge = 'hit' or badge = 'new'; -- хит НЕМЕСЕ жаңа

select name, color
from products
where not in_stock;                   -- тек тапсырыспен келетіндер

-- and пен or бірге келсе, жақша қойыңыз. Жақшасыз and бірінші орындалады.
select name, color, price, badge
from products
where (badge = 'hit' or badge = 'new') and price < 1000000;


-- ---------------------------------------------------------------------
-- 3.5. in және between
-- ---------------------------------------------------------------------
select name, color, price
from products
where color in ('Ақ', 'Графит', 'Беж');      -- тізімдегі мәндердің бірі

select name, color, price
from products
where price between 300000 and 500000;       -- 300 000 ≤ баға ≤ 500 000, шеттері де кіреді


-- ---------------------------------------------------------------------
-- 3.6. like / ilike: мәтін ішінен іздеу
-- ---------------------------------------------------------------------
--   %   кез келген мәтін (бос мәтін де)
--   _   дәл бір таңба
select name, color from products where name like 'Диван%';    -- 'Диван' сөзінен басталады

select name, color from products where color like '%емен%';   -- тек 'Ақ емен' шығады:
                                                               -- like үлкен-кіші әріпті ажыратады
select name, color from products where color ilike '%емен%';  -- 'Емен', 'Емен · беж', 'Ақ емен':
                                                               -- ilike әріп регистріне қарамайды


-- ---------------------------------------------------------------------
-- 3.7. NULL: "мәні жоқ"
-- ---------------------------------------------------------------------
-- NULL-ды = белгісімен салыстыруға болмайды, is null / is not null керек.
select name, color, old_price, price
from products
where old_price is not null;          -- жеңілдіктегі тауарлар

select name, address
from stores
where address is null;                -- мекенжайы жоқ дүкен

-- Тұзақ: мына сұрау ЕШТЕҢЕ қайтармайды. NULL = NULL нәтижесі true емес,
-- "белгісіз" (NULL) болады, ал where тек true жолдарды алады.
select name from stores where address = null;


-- ---------------------------------------------------------------------
-- 3.8. order by: сұрыптау
-- ---------------------------------------------------------------------
select name, color, price from products order by price;              -- арзанынан (asc, әдепкі)
select name, color, price from products order by price desc;         -- қымбатынан
select name, color, price from products order by name, price desc;   -- алдымен атауы, сосын бағасы


-- ---------------------------------------------------------------------
-- 3.9. limit және offset: беттерге бөлу (pagination)
-- ---------------------------------------------------------------------
select name, color, price
from products
order by price desc
limit 3;                              -- ең қымбат 3 тауар

select id, name, color
from products
order by id
limit 5 offset 5;                     -- 2-бет: алғашқы 5 жолды өткізіп, келесі 5-ін аламыз

-- Supabase JS-те: .range(5, 9) — дәл осы limit 5 offset 5.
-- limit-ті әрдайым order by-мен бірге жазыңыз, әйтпесе жолдардың реті
-- кепілдендірілмейді.


-- ---------------------------------------------------------------------
-- 3.10. distinct: қайталанбайтын мәндер
-- ---------------------------------------------------------------------
select distinct name
from products
order by name;                        -- 16 түстің ішінде 8 модель бар


-- ---------------------------------------------------------------------
-- 3.11. Есептелген бағандар және as (бүркеншік ат)
-- ---------------------------------------------------------------------
select name, color, old_price - price as discount
from products
where old_price is not null;

-- Бөліп төлеу 0-0-12: айына қанша төлейміз?
select name, color, price, price / 12 as monthly
from products;
-- Назар аударыңыз: integer / integer = integer. 1390000 / 12 = 115833,
-- бөлшек бөлігі жай ғана кесіліп қалады. Дәл есептеу үшін бір санды
-- бөлшек етіңіз (12.0), сосын round арқылы дөңгелектеңіз:
select name, color, price, round(price / 12.0) as monthly
from products;

-- Мәтінді біріктіру: ||
select name || ' · ' || color as title, price
from products;



--    • агрегат функциялар: count, sum, avg, min, max
--    • group by: жолдарды топтап, әр топқа есеп шығару
--    • having: дайын топтарды сүзу (where-ден айырмашылығы)
--    • filter және string_agg: бір сұраумен бірнеше есеп
--
--  Қалай орындау: 3-сабақтағыдай, сұрауларды бір-бірден белгілеп

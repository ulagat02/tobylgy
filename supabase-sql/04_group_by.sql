-- ---------------------------------------------------------------------
-- 4.1. count: санау
-- ---------------------------------------------------------------------
select count(*) from products;              -- барлық жол: 16
select count(old_price) from products;      -- old_price бос ЕМЕС жолдар: 4
select count(distinct name) from products;  -- неше түрлі модель: 8

-- count(*) барлық жолды санайды, ал count(баған) NULL мәндерді өткізіп жібереді.


-- ---------------------------------------------------------------------
-- 4.2. min, max, avg, sum
-- ---------------------------------------------------------------------
select min(price)        as cheapest,
       max(price)        as most_expensive,
       round(avg(price)) as average,
       sum(price)        as total
from products;


-- ---------------------------------------------------------------------
-- 4.3. group by: топтап есептеу
-- ---------------------------------------------------------------------
-- Әр модель бойынша: неше түсі бар және ең арзан бағасы
select name,
       count(*)   as colors,
       min(price) as price_from
from products
group by name
order by price_from;

-- Ереже: select-тегі әр баған не group by ішінде тұрады, не агрегат
-- функцияның (count, sum ...) ішінде болады. Мына сұрау ҚАТЕ береді,
-- себебі color топталмаған (бір модельде бірнеше түс бар, қайсысын алу керек?):
--   select name, color, count(*) from products group by name;


-- ---------------------------------------------------------------------
-- 4.4. Санат бойынша топтау
-- ---------------------------------------------------------------------
-- Санат атауын 6-сабақта join арқылы аламыз, әзірге тек category_id.
select category_id,
       count(*)          as products,
       round(avg(price)) as avg_price
from products
group by category_id
order by category_id;


-- ---------------------------------------------------------------------
-- 4.5. Бірнеше баған бойынша топтау
-- ---------------------------------------------------------------------
select in_stock, badge, count(*) as products
from products
group by in_stock, badge
order by in_stock desc, badge;


-- ---------------------------------------------------------------------
-- 4.6. having: топтардан кейінгі сүзгі
-- ---------------------------------------------------------------------
--   where   жолдарды топтауға ДЕЙІН сүзеді
--   having  дайын топтарды сүзеді (онда агрегат функция қолдануға болады)
select name, count(*) as colors
from products
group by name
having count(*) >= 3;                 -- 3 не одан көп түсі бар модельдер

select name, count(*) as colors_in_stock
from products
where in_stock                        -- алдымен тек қоймадағы жолдар қалады
group by name
having count(*) >= 2;                 -- сосын қоймада 2+ түсі бар модельдер


-- ---------------------------------------------------------------------
-- 4.7. filter: шартты санау
-- ---------------------------------------------------------------------
-- Бір сұраумен бірнеше түрлі есеп:
select count(*)                                    as total,
       count(*) filter (where in_stock)            as in_stock,
       count(*) filter (where not in_stock)        as on_order,
       count(*) filter (where old_price is not null) as on_sale
from products;


-- ---------------------------------------------------------------------
-- 4.8. string_agg: мәндерді бір жолға жинау
-- ---------------------------------------------------------------------
select name,
       string_agg(color, ', ' order by price) as colors,
       min(price) as price_from
from products
group by name
order by name;


-- ---------------------------------------------------------------------
-- 4.9. Дүкендер бойынша
-- ---------------------------------------------------------------------
select city,
       count(*)              as stores,
       round(avg(rating), 2) as avg_rating
from stores
group by city;



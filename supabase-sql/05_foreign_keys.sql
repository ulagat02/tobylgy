-- Келесі сабақтардың деректері бұзылмауы үшін деректі өзгертетін
-- тапсырмаларды "сынақ режимінде" орындаңыз. Жаңа query бетін ашып,
-- командаларды begin; мен rollback; арасына жазыңыз:
--
--     begin;
--       insert ...;           -- сіздің командаларыңыз
--       select ...;           -- нәтижені тексеру
--     rollback;               -- бәрі кері қайтарылады
--
-- SQL Editor нәтиже беретін соңғы сұрауды (select) көрсетеді, ал rollback
-- барлық өзгерісті жояды. Мұны тек жеке query бетінде қолданыңыз: сабақ
-- файлының ішінде begin/rollback одан бұрынғы командаларды да жояды.
--
-- Тапсырма 5-1. (сынақ режимінде) Бауыржан К.-ға symbat дүкенінен
--   тапсырыс жасаңыз: 1 аспалы шам Ay, қазіргі бағасымен. Соңында
--   тапсырыстар мен құрамын select арқылы көрсетіңіз.
--
-- Тапсырма 5-2. (сынақ режимінде) 1-тапсырысты (ең бірінші тапсырыс)
--   өшіріңіз. Оның order_items жолдарына не болды? Неге?
--
-- Тапсырма 5-3. Ойланыңыз: бір тапсырыста ақ Tamir диваны екі жолға
--   жазыла ала ма? Екі диван керек болса, қалай жазамыз?

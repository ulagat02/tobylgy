-- =====================================================================
--  5-САБАҚ · КЕСТЕЛЕР АРАСЫНДАҒЫ БАЙЛАНЫС (FOREIGN KEY)
-- =====================================================================
--  Не үйренесіз:
--    • бірге-көп (one-to-many): бір клиенттің көп тапсырысы
--    • көпке-көп (many-to-many): тапсырыс ↔ тауар, аралық кесте арқылы
--    • on delete: негізгі жол өшкенде байланысқан жолдарға не болады
--    • индекс: сыртқы кілттерді жылдам іздеу үшін
--
--  Қалай орындау: файлды толық көшіріп, бір рет Run басыңыз. Ол 4 жаңа
--  кесте құрып, оларға сынақ деректерін енгізеді. Содан кейін оқыңыз.
--
--  Байланыстар (A → B: A кестесінде B-ға сілтейтін сыртқы кілт бар):
--    products    → categories
--    orders      → customers, stores
--    order_items → orders, products
--    reviews     → products, customers
-- =====================================================================


-- ---------------------------------------------------------------------
-- 5.1. customers (клиенттер)
-- ---------------------------------------------------------------------
create table customers (
  id         bigint generated always as identity primary key,
  full_name  text not null,
  phone      text not null unique,
  city       text not null default 'Қызылорда',
  created_at timestamptz not null default now()
);


-- ---------------------------------------------------------------------
-- 5.2. orders (тапсырыстар): бірге-көп байланыс
-- ---------------------------------------------------------------------
-- Бір клиенттің көп тапсырысы болуы мүмкін, бірақ әр тапсырыс бір ғана
-- клиентке тиесілі. Сондықтан customer_id бағаны orders кестесінде тұрады.
create table orders (
  id          bigint generated always as identity primary key,
  customer_id bigint not null references customers (id),
  store_id    bigint not null references stores (id),
  status      text not null default 'new'
              check (status in ('new', 'paid', 'delivered', 'cancelled')),
  payment     text not null default 'card'
              check (payment in ('cash', 'card', 'installment')),
  created_at  timestamptz not null default now()
);

--   status   new — жаңа, paid — төленді, delivered — жеткізілді,
--            cancelled — бас тартылды
--   payment  cash — қолма-қол, card — карта,
--            installment — бөліп төлеу (0-0-12)


-- ---------------------------------------------------------------------
-- 5.3. order_items (тапсырыс құрамы): көпке-көп байланыс
-- ---------------------------------------------------------------------
-- Бір тапсырыста бірнеше тауар, бір тауар көп тапсырыста бола алады.
-- Мұндай байланыс аралық кесте арқылы жасалады: әр жолы "қай тапсырыста,
-- қай тауар, неше дана, қандай бағамен".
create table order_items (
  order_id   bigint not null references orders (id) on delete cascade,
  product_id bigint not null references products (id),
  quantity   integer not null default 1 check (quantity > 0),
  unit_price integer not null check (unit_price > 0),
  primary key (order_id, product_id)
);

--   primary key (order_id, product_id)
--        құрама кілт: бір тапсырыста бір тауар бір-ақ рет жазылады
--        (екі дана керек болса, quantity = 2).
--   unit_price
--        САТЫЛҒАН кездегі баға. Тауардың бағасы кейін өзгеруі мүмкін,
--        ал ескі тапсырыстың сомасы өзгермеуі керек.


-- ---------------------------------------------------------------------
-- 5.4. reviews (пікірлер)
-- ---------------------------------------------------------------------
create table reviews (
  id          bigint generated always as identity primary key,
  product_id  bigint not null references products (id) on delete cascade,
  customer_id bigint references customers (id) on delete set null,
  rating      smallint not null check (rating between 1 and 5),
  body        text,
  created_at  timestamptz not null default now()
);


-- ---------------------------------------------------------------------
-- 5.5. on delete: негізгі жол өшкенде не болады?
-- ---------------------------------------------------------------------
--   (ештеңе жазылмаса)  ӨШІРУГЕ ЖОЛ БЕРМЕЙДІ: тапсырысы бар клиентті
--                       өшіру қате береді. Деректі абайсыз жоғалтпаймыз.
--   on delete cascade   бірге өшіреді: тапсырыс өшсе, оның order_items
--                       жолдары да өшеді.
--   on delete set null  сілтемені NULL етеді: клиент өшсе, оның пікірі
--                       қалады, бірақ customer_id бос болады.


-- ---------------------------------------------------------------------
-- 5.6. Индекстер
-- ---------------------------------------------------------------------
-- Индекс — кітаптың соңындағы көрсеткіш сияқты: керек жолды бүкіл
-- кестені ақтармай табуға көмектеседі. Postgres primary key мен unique
-- бағандарына индексті өзі жасайды, ал сыртқы кілттерге ЖАСАМАЙДЫ.
-- Supabase-тің Performance Advisor бөлімі индекссіз сыртқы кілттерді
-- ескертеді. Сондықтан оларды өзіміз қосамыз:
create index on products (category_id);
create index on orders (customer_id);
create index on orders (store_id);
create index on order_items (product_id);
create index on reviews (product_id);
create index on reviews (customer_id);

-- order_items (order_id) үшін бөлек индекс керек емес: ол primary key
-- (order_id, product_id) ішінде бірінші тұр, сол индекс жарайды.


-- ---------------------------------------------------------------------
-- 5.7. RLS (1-сабақтағы ереже: public-тегі әр кестеге)
-- ---------------------------------------------------------------------
alter table customers   enable row level security;
alter table orders      enable row level security;
alter table order_items enable row level security;
alter table reviews     enable row level security;


